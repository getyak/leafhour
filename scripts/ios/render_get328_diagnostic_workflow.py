"""Render the no-post workflow from exact reviewed source; never run a job."""
import argparse
import hashlib
import json
from pathlib import Path

from hosted_get328_diagnostic_bootstrap import CONTROLLER_FILES, UPLOADER_BYTES, UPLOADER_SHA256

WORKFLOW = '.github/workflows/get328-environment-once.yml'


def _bytes(root, relative):
    path = root / relative
    if path.is_symlink() or not path.is_file() or path.resolve() != path.absolute():
        raise ValueError('source must be an existing non-symlink file: ' + relative)
    raw = path.read_bytes()
    if not raw or len(raw) > 8 * 1024**2:
        raise ValueError('source size invalid: ' + relative)
    return raw


def asset_manifest(root):
    root = Path(root).resolve()
    result = []
    for relative in CONTROLLER_FILES:
        raw = _bytes(root, relative)
        result.append(dict(scope='controller', path=relative, bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest()))
    result.append(dict(scope='uploader', path='dist/upload/index.js', bytes=UPLOADER_BYTES, sha256=UPLOADER_SHA256))
    return result


def render_workflow(root):
    root = Path(root).resolve()
    core = _bytes(root, 'scripts/ios/hosted_get328_diagnostic_core.py').decode('utf-8')
    bootstrap_source = _bytes(root, 'scripts/ios/hosted_get328_diagnostic_bootstrap.py').decode('utf-8')
    if not core.endswith('\n') or not bootstrap_source.endswith('\n'):
        raise ValueError('inline source must retain its final newline')
    manifest = asset_manifest(root)
    python = ('# BEGIN CORE SOURCE\n' + core + '# END CORE SOURCE\n'
              "import sys\nsys.modules['hosted_get328_diagnostic_core'] = sys.modules['__main__']\n"
              '# BEGIN BOOTSTRAP SOURCE\n' + bootstrap_source + '# END BOOTSTRAP SOURCE\n'
              'SOURCE_ASSET_MANIFEST = ' + json.dumps(manifest, indent=2) + '\n'
              'bootstrap(SOURCE_ASSET_MANIFEST)\n')
    inline = ''.join(('          ' + line) if line != '\n' else line
                     for line in python.splitlines(keepends=True))
    return '''# Generated by scripts/ios/render_get328_diagnostic_workflow.py; do not edit the inline copies.
name: GET-328 environment diagnostic once

on:
  push:
    branches: ['codex/get-328-environment-once/**']

permissions:
  contents: read

concurrency:
  group: get328-hosted-environment-diagnostic-once
  cancel-in-progress: false

jobs:
  diagnose:
    # A pending public comment is not a grant. No ordinary PR/main/manual entry.
    if: >-
      github.repository == 'getyak/leafhour' &&
      github.event_name == 'push' &&
      github.event.created == true &&
      github.event.deleted == false &&
      github.event.forced == false &&
      github.actor == 'kubbot' &&
      github.actor_id == '124379614' &&
      github.triggering_actor == github.actor &&
      github.run_attempt == '1'
    runs-on: macos-26-intel
    timeout-minutes: 6
    env:
      DEVELOPER_DIR: /Applications/Xcode_26.6.app/Contents/Developer
      GET328_GRANT_COMMENT_ID: '6703465445'
      GET328_GRANT_ISSUER_ID: '124379614'
    steps:
      - name: Stamp once and fetch only the fixed public source closure
        id: bootstrap
        timeout-minutes: 6
        shell: bash
        run: |
          python3 -B - <<'PY'
''' + inline + '''          PY

      - name: Run only the separately admitted bounded diagnostic
        if: success() && steps.bootstrap.outputs.ready == 'true'
        uses: ./controller/.github/actions/get328-diagnostic
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rendered = render_workflow(args.root)
    destination = args.root / WORKFLOW
    if args.check:
        if not destination.exists() or destination.read_bytes() != rendered.encode('utf-8'):
            raise SystemExit('generated diagnostic workflow differs from reviewed source')
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(rendered, encoding='utf-8')


if __name__ == '__main__':
    main()
