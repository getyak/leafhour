// Keep inline bytes independent of a serverless bundler's identifier rewrites.
import {writeFile,readFile} from 'node:fs/promises';
import {UI_FIRST_PAINT_SCRIPT} from '../app/ui-first-paint-bootstrap.mjs';
const target=new URL('../server/ui-first-paint-script.mjs',import.meta.url);
const source='// Generated by tools/build-ui-first-paint-script.mjs. No runtime/user data.\nexport const UI_FIRST_PAINT_SCRIPT='+JSON.stringify(UI_FIRST_PAINT_SCRIPT)+';\n';
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==source)throw Error('First-paint script bytes are stale; regenerate before release.');}
else await writeFile(target,source);
